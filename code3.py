#Comparison operators
a =int(input("Enter a number: "))
b = int(input("Enter another number: "))

sum = a + b
print("The sum of the two numbers is:", sum)

sum = a - b
print("The difference of the two numbers is:", sum)

sum = a * b
print("The product of the two numbers is:", sum)

sum = a / b
print("The quotient of the two numbers is:", sum)

sum = a % b
print("The remainder of the two numbers is:", sum)